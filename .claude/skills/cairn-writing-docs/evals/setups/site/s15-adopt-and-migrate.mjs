/** @param {string} root */
export default function setup(root) {
  const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
  const engine = pkg.dependencies['@glw907/cairn-cms'];
  const dev = (name) => pkg.devDependencies[name];
  const bare = {
    name: 'field-notes',
    private: true,
    version: '0.0.1',
    type: 'module',
    scripts: {
      dev: 'vite dev',
      build: 'vite build',
      preview: 'wrangler dev',
      check: 'svelte-kit sync && svelte-check --tsconfig ./tsconfig.json',
      'cf-typegen': 'wrangler types --include-runtime=false',
    },
    dependencies: { '@glw907/cairn-cms': engine },
    devDependencies: Object.fromEntries(
      [
        '@cloudflare/workers-types',
        '@sveltejs/adapter-cloudflare',
        '@sveltejs/kit',
        '@sveltejs/vite-plugin-svelte',
        '@types/node',
        'svelte',
        'svelte-check',
        'typescript',
        'vite',
        'wrangler',
      ].map((name) => [name, dev(name)]),
    ),
  };
  writeFileSync(join(root, 'package.json'), `${JSON.stringify(bare, null, 2)}\n`);

  for (const gone of ['src', 'migrations', '.github', 'vitest.config.ts', 'e2e', 'scripts']) {
    rmSync(join(root, gone), { recursive: true, force: true });
  }
  mkdirSync(join(root, 'src/routes'), { recursive: true });
  writeFileSync(join(root, 'src/app.html'), APP_HTML);
  writeFileSync(join(root, 'src/app.d.ts'), APP_D_TS);
  writeFileSync(join(root, 'src/routes/+layout.svelte'), LAYOUT);
  writeFileSync(join(root, 'src/routes/+page.svelte'), HOME);
  writeFileSync(join(root, 'vite.config.ts'), VITE_CONFIG);
  writeFileSync(join(root, 'wrangler.jsonc'), WRANGLER);
  writeFileSync(join(root, 'worker-configuration.d.ts'), WORKER_TYPES);

  mkdirSync(join(root, 'old-content/posts'), { recursive: true });
  for (const [name, text] of Object.entries(OLD_POSTS)) {
    writeFileSync(join(root, 'old-content/posts', name), text);
  }
}
