// Setup for `S15-adopt-and-migrate`: turns the emitted site into the starting point of an existing
// SvelteKit app that has never had cairn. The app's source, migrations, workflow, and test config
// are removed and replaced with what `sv create` leaves on the Cloudflare adapter: a home page, a
// plain Vite config, a bare Wrangler config, and a package.json with no `imports` map. Beside it
// sit four Jekyll-style posts in `old-content/posts` with the usual faults: an off-shape filename,
// an unquoted timestamp whose UTC day is not its filename's day, a `layout` key, a `summary`
// that stands for a description, and a `published: false` draft.
//
// What this setup gives up: the engine and its peers stay declared in package.json and installed in
// node_modules, because a case run cannot depend on the npm registry. The "install the engine" step
// of the adoption path therefore never happens here; every other step of it does.
