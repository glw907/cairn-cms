// Generates the two files that carry a theme's daisyUI names from its manifest's `colorModes`, so
// the names have one source: `src/theme/theme-names.ts`, which the toggle imports, and the cookie
// regex in `src/app.html`, whose inline script runs before first paint and cannot import anything.
//
//   node scripts/theme/theme-names.mjs <themeDir> <siteDir>
//
// The regex names both themes on purpose: after a rename, a returning visitor's stale cookie fails
// it and the page falls back to the system scheme, where a regex that accepted any name would pin
// that visitor to the default block for up to a year.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

/** The cookie the toggle persists a visitor's choice to; the chassis toggle and `app.html` agree on it. */
export const COOKIE_NAME = 'cairn-site-theme';

const START = 'cairn-theme-names:start';
const END = 'cairn-theme-names:end';
const NAME = /^[a-z][a-z0-9-]*$/;

/**
 * The text of `theme-names.ts` for a theme's two daisyUI names.
 * @param {{ light: string, dark: string }} colorModes
 * @returns {string}
 */
export function renderThemeNames({ light, dark }) {
  return `// Generated by scripts/theme/theme-names.mjs from the theme manifest's colorModes. Do not edit.
// The light/dark toggle's one config: the two daisyUI theme names and the cookie that remembers a
// visitor's choice. \`SiteHeader.svelte\` imports it, so a theme rename reaches the toggle.
import type { ThemeToggleConfig } from '#chassis/theme-toggle.js';

/** The two explicit theme choices; the theme's stylesheet defines both as named daisyUI themes. */
export type Theme = '${light}' | '${dark}';

/** This theme's names and cookie, fed to the chassis toggle mechanism. */
export const themeConfig: ThemeToggleConfig<Theme> = {
  light: '${light}',
  dark: '${dark}',
  cookieName: '${COOKIE_NAME}',
};
`;
}

/**
 * Replaces the lines between the two marker comments in `app.html` with the cookie regex line for
 * the given names. Throws, naming the marker, when either is missing.
 * @param {string} html
 * @param {{ light: string, dark: string }} colorModes
 * @returns {string}
 */
export function rewriteAppHtml(html, { light, dark }) {
  const lines = html.split('\n');
  const start = lines.findIndex((l) => l.includes(START));
  const end = lines.findIndex((l) => l.includes(END));
  if (start === -1) throw new Error(`app.html has no ${START} marker`);
  if (end === -1) throw new Error(`app.html has no ${END} marker`);
  if (end <= start) throw new Error(`app.html carries ${END} before ${START}`);
  const indent = (/^\s*/.exec(lines[start]) ?? [''])[0];
  const line = `${indent}var match = document.cookie.match(/(?:^|; )${COOKIE_NAME}=(${dark}|${light})(?:;|$)/);`;
  return [...lines.slice(0, start + 1), line, ...lines.slice(end)].join('\n');
}

/**
 * Throws unless both color-mode names are lowercase daisyUI theme names. The names are written into
 * code, so nothing reaches a file before this passes.
 * @param {{ light: string, dark: string }} colorModes
 * @returns {void}
 */
export function assertColorModes(colorModes) {
  for (const key of /** @type {const} */ (['light', 'dark'])) {
    if (typeof colorModes?.[key] !== 'string' || !NAME.test(colorModes[key])) {
      throw new Error(`colorModes.${key} must be a lowercase daisyUI theme name, got ${JSON.stringify(colorModes?.[key])}`);
    }
  }
}

/**
 * Writes `theme-names.ts` and rewrites `app.html` under a site directory.
 * @param {string} siteDir
 * @param {{ light: string, dark: string }} colorModes
 * @returns {void}
 */
export function generateThemeNames(siteDir, colorModes) {
  assertColorModes(colorModes);
  const htmlPath = path.join(siteDir, 'src/app.html');
  const rewritten = rewriteAppHtml(readFileSync(htmlPath, 'utf8'), colorModes);
  writeFileSync(path.join(siteDir, 'src/theme/theme-names.ts'), renderThemeNames(colorModes));
  writeFileSync(htmlPath, rewritten);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const [themeDir, siteDir] = process.argv.slice(2);
  if (!themeDir || !siteDir) {
    console.error('usage: theme-names.mjs <themeDir> <siteDir>');
    process.exit(2);
  }
  const manifest = JSON.parse(readFileSync(path.join(themeDir, 'cairn-theme.json'), 'utf8'));
  generateThemeNames(siteDir, manifest.colorModes);
}
