import { createHash } from 'node:crypto';
import { describe, it, expect, vi, afterEach } from 'vitest';
import { buildICalendarResponse } from '../../lib/delivery/responses.js';
import type { ICalendar, ICalendarEvent } from '../../lib/delivery/icalendar.js';

const encoder = new TextEncoder();

async function bodyBytes(calendar: ICalendar): Promise<Uint8Array> {
  const res = buildICalendarResponse(calendar);
  return new Uint8Array(await res.arrayBuffer());
}

async function bodyText(calendar: ICalendar): Promise<string> {
  return new TextDecoder('utf-8', { fatal: true }).decode(await bodyBytes(calendar));
}

function oneEvent(event: ICalendarEvent): ICalendar {
  return { name: 'N', productId: '-//X//Y//EN', stamp: new Date('2027-01-01T00:00:00Z'), events: [event] };
}

function allDay(summary: string): ICalendarEvent {
  return { uid: 'u@example.org', start: '2027-06-05', summary };
}

const calendar: ICalendar = {
  name: 'Example Club events',
  productId: '-//Example Club//Events//EN',
  stamp: new Date('2027-01-01T00:00:00Z'),
  events: [
    { uid: 'map-night-2027-01-13@example.org', start: new Date('2027-01-14T03:30:00Z'), end: new Date('2027-01-14T05:00:00Z'), summary: 'Map night', location: 'Clubhouse, upper room', url: 'https://example.org/events/map-night' },
    { uid: 'field-day-2027-06-05@example.org', start: '2027-06-05', summary: 'Field day' },
    { uid: 'waxing-course-2027-06-11@example.org', start: '2027-06-11', end: '2027-06-13', summary: 'Waxing course', description: 'Three days at the upper lot. Bring skis, boots, and lunch.\nWaxes are provided.' },
    { uid: 'field-day-2027-06-19@example.org', start: new Date('2027-06-20T01:00:00Z'), summary: 'Cancelled: Field day', status: 'cancelled' },
  ],
};

// Written by hand from RFC 5545 and checked by a published parser, never generated by the builder.
const fixtureLines = [
  'BEGIN:VCALENDAR',
  'PRODID:-//Example Club//Events//EN',
  'VERSION:2.0',
  'NAME:Example Club events',
  'X-WR-CALNAME:Example Club events',
  'BEGIN:VEVENT',
  'UID:map-night-2027-01-13@example.org',
  'DTSTAMP:20270101T000000Z',
  'DTSTART:20270114T033000Z',
  'DTEND:20270114T050000Z',
  'SUMMARY:Map night',
  'LOCATION:Clubhouse\\, upper room',
  'URL:https://example.org/events/map-night',
  'END:VEVENT',
  'BEGIN:VEVENT',
  'UID:field-day-2027-06-05@example.org',
  'DTSTAMP:20270101T000000Z',
  'DTSTART;VALUE=DATE:20270605',
  'DTEND;VALUE=DATE:20270606',
  'SUMMARY:Field day',
  'END:VEVENT',
  'BEGIN:VEVENT',
  'UID:waxing-course-2027-06-11@example.org',
  'DTSTAMP:20270101T000000Z',
  'DTSTART;VALUE=DATE:20270611',
  'DTEND;VALUE=DATE:20270614',
  'SUMMARY:Waxing course',
  'DESCRIPTION:Three days at the upper lot. Bring skis\\, boots\\, and lunch.\\nW',
  ' axes are provided.',
  'END:VEVENT',
  'BEGIN:VEVENT',
  'UID:field-day-2027-06-19@example.org',
  'DTSTAMP:20270101T000000Z',
  'DTSTART:20270620T010000Z',
  'SUMMARY:Cancelled: Field day',
  'STATUS:CANCELLED',
  'END:VEVENT',
  'END:VCALENDAR',
];
const fixture = fixtureLines.join('\r\n') + '\r\n';

/** Split a body into physical lines, dropping the empty tail after the final CRLF. */
function physicalLines(text: string): string[] {
  const lines = text.split('\r\n');
  expect(lines.pop()).toBe('');
  return lines;
}

/** Undo RFC 5545 section 3.1 folding and return the named property's value. */
function unfoldedValue(text: string, name: string): string | undefined {
  const line = text.replace(/\r\n /g, '').split('\r\n').find((l) => l.startsWith(`${name}:`));
  return line?.slice(name.length + 1);
}

describe('buildICalendarResponse: an RFC 5545 feed of plain events', () => {
  afterEach(() => {
    vi.useRealTimers();
  });

  it('writes the four-event feed byte for byte as the hand-written fixture', async () => {
    expect(createHash('sha256').update(fixture).digest('hex')).toBe(
      'cc439742c23f4953b5b8bb5c4e61a57e693b2638a15d19124350115857b82faf',
    );
    expect(await bodyBytes(calendar)).toEqual(encoder.encode(fixture));
  });

  it('carries each required property of the four-event feed', async () => {
    const text = await bodyText(calendar);
    expect(text.endsWith('\r\n')).toBe(true);
    expect(text.replace(/\r\n/g, '')).not.toMatch(/[\r\n]/);
    const lines = physicalLines(text);
    expect(lines).toContain('VERSION:2.0');
    expect(lines).toContain('PRODID:-//Example Club//Events//EN');
    expect(lines.filter((l) => l.startsWith('DTSTAMP:'))).toHaveLength(4);
    const timedStarts = lines.filter((l) => l.startsWith('DTSTART:'));
    expect(timedStarts).toHaveLength(2);
    for (const line of timedStarts) expect(line.endsWith('Z')).toBe(true);
    expect(lines.filter((l) => l === 'STATUS:CANCELLED')).toHaveLength(1);
    expect(lines).toContain('DTEND;VALUE=DATE:20270614');
  });

  it.each([
    ['two-octet', 'é'.repeat(60)],
    ['four-octet', '🎿'.repeat(30)],
  ])('folds a long %s summary within 75 octets without splitting a character', async (_label, summary) => {
    const bytes = await bodyBytes(oneEvent(allDay(summary)));
    const text = new TextDecoder().decode(bytes);
    for (const line of physicalLines(text)) {
      const lineBytes = encoder.encode(line);
      expect(lineBytes.length).toBeLessThanOrEqual(75);
      expect(() => new TextDecoder('utf-8', { fatal: true }).decode(lineBytes)).not.toThrow();
    }
    expect(physicalLines(text).filter((l) => l.startsWith(' ')).length).toBeGreaterThan(0);
    expect(unfoldedValue(text, 'SUMMARY')).toBe(summary);
  });

  it.each([
    ['a newline', 'a,b;c\\d\ne'],
    ['a CRLF', 'a,b;c\\d\r\ne'],
    ['a lone carriage return', 'a,b;c\\d\re'],
  ])('escapes a comma, a semicolon, a backslash, and %s in TEXT', async (_label, summary) => {
    const lines = physicalLines(await bodyText(oneEvent(allDay(summary))));
    expect(lines).toContain('SUMMARY:a\\,b\\;c\\\\d\\ne');
  });

  it('writes an empty calendar as the header and footer with no event', async () => {
    const text = await bodyText({ name: 'Example Club events', productId: '-//Example Club//Events//EN', events: [] });
    expect(physicalLines(text)).toEqual([
      'BEGIN:VCALENDAR',
      'PRODID:-//Example Club//Events//EN',
      'VERSION:2.0',
      'NAME:Example Club events',
      'X-WR-CALNAME:Example Club events',
      'END:VCALENDAR',
    ]);
  });

  it.each([
    ['2027-12-31', '20280101'],
    ['2028-02-28', '20280229'],
  ] as const)('writes the exclusive end after an inclusive all-day end of %s', async (end, written) => {
    const lines = physicalLines(await bodyText(oneEvent({ uid: 'u@example.org', start: '2027-12-30', end, summary: 'S' })));
    expect(lines).toContain(`DTEND;VALUE=DATE:${written}`);
  });

  it('stamps every event with the build time when no stamp is given', async () => {
    vi.useFakeTimers();
    vi.setSystemTime(new Date('2027-03-01T12:00:00Z'));
    const lines = physicalLines(await bodyText({ name: 'N', productId: '-//X//Y//EN', events: [allDay('S')] }));
    expect(lines).toContain('DTSTAMP:20270301T120000Z');
  });

  it('writes no repeat rule, recurrence id, or sequence number', async () => {
    const text = await bodyText(calendar);
    for (const name of ['RRULE', 'RECURRENCE-ID', 'SEQUENCE']) expect(text).not.toContain(name);
  });
});
