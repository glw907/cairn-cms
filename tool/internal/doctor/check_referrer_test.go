// TestIsCatchAllHeadersPathGapCase proves the net/url port still recognizes the absolute-URL
// spelling of the catch-all glob.
func TestIsCatchAllHeadersPathGapCase(t *testing.T) {
	if !isCatchAllHeadersPath("https://example.com/*") {
		t.Fatal("isCatchAllHeadersPath(https://example.com/*) = false, want true")
	}
	if isCatchAllHeadersPath("/admin/*") {
		t.Fatal("isCatchAllHeadersPath(/admin/*) = true, want false")
	}
}

// TestHooksSetsBlanketNoReferrerGapCase is the named gap case: a route-scoped no-referrer write
// within the six-line window above must not read as blanket. Proven directly against the helper,
// which fails without the window scan: a bare mention-of-both-tokens match finds the write and
// returns true regardless of the nearby pathname guard.
func TestHooksSetsBlanketNoReferrerGapCase(t *testing.T) {
	if hooksSetsBlanketNoReferrer(hooksScoped) {
		t.Fatal("hooksSetsBlanketNoReferrer(hooksScoped) = true, want false: the write is scoped by pathname within the six-line window")
	}
	if !hooksSetsBlanketNoReferrer(hooksBlanket) {
		t.Fatal("hooksSetsBlanketNoReferrer(hooksBlanket) = false, want true: no scoping guard is present")
	}
}

// TestParseHeadersFileGapCase is the named gap case: a comment line interleaved inside a
// _headers block must not split it. Proven directly against the parser, which fails without the
// comment-skip: a naive line scan reads the # line as a new path line and starts a second,
// header-less block, losing the real block's headers.
func TestParseHeadersFileGapCase(t *testing.T) {
	blocks := parseHeadersFile(headersBlanketWithComment)
	if len(blocks) != 1 {
		t.Fatalf("parseHeadersFile returned %d blocks, want 1 (the comment must not split the block): %+v", len(blocks), blocks)
	}
	if blocks[0].path != "/*" {
		t.Errorf("blocks[0].path = %q, want /*", blocks[0].path)
	}
	if len(blocks[0].headers) != 1 || blocks[0].headers[0] != "Referrer-Policy: no-referrer" {
		t.Errorf("blocks[0].headers = %+v, want [\"Referrer-Policy: no-referrer\"]", blocks[0].headers)
	}
}

// TestIsBlanketNoReferrerHeaderLineGapCase is the named gap case: a fallback list's effective
// value is its last token, so no-referrer earlier in the list must not count.
func TestIsBlanketNoReferrerHeaderLineGapCase(t *testing.T) {
	if !isBlanketNoReferrerHeaderLine("Referrer-Policy: strict-origin, no-referrer") {
		t.Error("no-referrer as the last token must be blanket")
	}
	if isBlanketNoReferrerHeaderLine("Referrer-Policy: no-referrer, strict-origin-when-cross-origin") {
		t.Error("no-referrer earlier in the list, not last, must not be blanket")
	}
}
